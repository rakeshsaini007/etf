export function enrichAssetWithStatus(item: NseAsset): NseAsset {
  let status: NseAsset['status'] = 'Neutral';
  if (item.rsi <= 30) status = 'Extremely Oversold';
  else if (item.rsi <= 40) status = 'Oversold';
  else if (item.rsi <= 60) status = 'Neutral';
  else if (item.rsi <= 70) status = 'Bullish';
  else status = 'Overbought';

  return {
    ...item,
    status
  };
}

export function getInitialEnrichedData(): NseAsset[] {
  return RAW_SHEET_DATA.map(enrichAssetWithStatus);
}
